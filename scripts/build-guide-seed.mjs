// Generate supabase/seed_counter_guides.sql: one rule-derived playbook row per
// hero pair. Run: node scripts/build-guide-seed.mjs
// Only pairs with a clear edge (|score| >= good band) are stored, so the table
// carries the matchups worth reading; the client computes the rest on demand.
import {writeFileSync} from 'node:fs'
import {playbook} from '../src/playbook.mjs'
import {BANDS} from '../src/matchup.mjs'
import det from '../src/hero-details.json' with {type:'json'}
import heroesRaw from '../src/heroes.json' with {type:'json'}
import tags from '../src/hero-tags.json' with {type:'json'}

const heroes=Array.isArray(heroesRaw)?heroesRaw:Object.values(heroesRaw)
const q=s=>"'"+String(s).replace(/'/g,"''")+"'"
const arr=a=>'array['+a.map(q).join(',')+']::text[]'
const rows=[]
for(const a of heroes)for(const b of heroes){
  if(a.id===b.id)continue
  const p=playbook(a,b,{details:det,tags})
  if(!p||Math.abs(p.score)<BANDS.good)continue
  const phases=Object.fromEntries(Object.entries(p.phases).filter(([,v])=>v.length))
  rows.push('('+[q(a.id),q(b.id),p.score,q(p.band),arr(p.edges),q(JSON.stringify({plan:p.plan,...phases}))+'::jsonb',arr(p.items.map(i=>i.name))].join(',')+')')
}
const chunks=[]
for(let i=0;i<rows.length;i+=500)chunks.push(rows.slice(i,i+500))
const sql=['-- Generated by scripts/build-guide-seed.mjs. Rule-derived, not win rates.','begin;',
  "delete from public.war_counter_guides where source='rule';",
  ...chunks.map(c=>'insert into public.war_counter_guides(hero_id,enemy_id,score,band,edges,phases,items) values\n'+c.join(',\n')+';'),
  'commit;'].join('\n')
writeFileSync('supabase/seed_counter_guides.sql',sql)
console.log('rows',rows.length,'bytes',sql.length)
