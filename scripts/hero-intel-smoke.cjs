const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright')
const assert=require('node:assert/strict')
const root=process.env.SMOKE_URL||'http://127.0.0.1:5173'
;(async()=>{
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox']})
const errors=[]
try{
 const pc=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'no-preference',permissions:['clipboard-read','clipboard-write']})
 pc.on('pageerror',e=>errors.push(e.message))
 await pc.goto(root,{waitUntil:'domcontentloaded'})
 await pc.getByRole('button',{name:'ทีมเรา แครี่ เลือกฮีโร่'}).click()
 const tile=pc.getByRole('button',{name:'ฮีโร่ Hayate',exact:true})
 await tile.hover()
 assert.equal(await tile.evaluate(el=>getComputedStyle(el,'::after').animationName),'esport-sweep')
 await tile.click()
 await pc.getByRole('button',{name:'รายละเอียดฮีโร่และบิลด์'}).click()
 const modal=pc.getByRole('dialog',{name:'Hayate',exact:true})
 await modal.getByText("Fafnir's Talon",{exact:true}).waitFor()
 await modal.getByText('Awake',{exact:true}).waitFor()
 await modal.getByText('Flicker',{exact:true}).waitFor()
 await modal.getByText('Sacred Protection',{exact:true}).waitFor()
 await modal.getByText('ลำดับความสำคัญ',{exact:true}).waitFor()
 await modal.getByRole('button',{name:'สกิล 1',exact:true}).click()
 await modal.getByText('Shuriken Toss',{exact:true}).waitFor()
 await modal.getByText(/ปาดาวกระจายไปด้านหน้า/).waitFor()
 await modal.getByRole('button',{name:/Death Sickle/}).click()
 await modal.getByText('ใช้เป็นทางเลือกเมื่อต้องเผื่อจังหวะรอดจากดาเมจปิดงาน').waitFor()
 await modal.getByRole('button',{name:'คัดลอกบิลด์'}).click()
 await modal.getByText('คัดลอกบิลด์แล้ว').waitFor()
 assert((await pc.evaluate(()=>navigator.clipboard.readText())).includes("War Boots → Fafnir's Talon"))
 assert.equal(await pc.locator('.draft-panel .slot-arrival').count(),0)
 await modal.locator('.intel-body').evaluate(el=>el.scrollTop=0)
 if(process.env.SMOKE_SCREENSHOTS)await pc.screenshot({path:'/tmp/rov-v3-desktop.png',timeout:20000})
 await modal.getByRole('searchbox',{name:'ค้นหาฮีโร่อื่น'}).fill('Evita')
 await modal.getByRole('button',{name:/Evita/}).click()
 const ev=pc.getByRole('dialog',{name:'Evita',exact:true})
 await ev.getByText('ยังไม่มีบิลด์ที่ยืนยันได้สำหรับฮีโร่นี้').waitFor()
 await ev.getByText('Umbral Origin',{exact:true}).waitFor()
 await pc.keyboard.press('Escape')
 await ev.waitFor({state:'hidden'})
 await pc.getByRole('button',{name:'ยืนยันเลือก',exact:true}).click()
 await pc.getByRole('button',{name:'ทีมเรา แครี่ Hayate'}).waitFor()
 await pc.getByRole('button',{name:'ลดการเคลื่อนไหว'}).click()
 await tile.hover()
 assert.equal(await tile.evaluate(el=>getComputedStyle(el,'::after').animationName),'none')

 const phone=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:'reduce'})
 phone.on('pageerror',e=>errors.push(e.message))
 await phone.goto(root,{waitUntil:'domcontentloaded'})
 await phone.getByRole('button',{name:'คู่แข่ง แครี่ เลือกฮีโร่'}).tap()
 const sheet=phone.getByRole('dialog',{name:'คลังฮีโร่',exact:true})
 await sheet.getByRole('button',{name:'รายละเอียด Hayate',exact:true}).tap()
 const hm=phone.getByRole('dialog',{name:'Hayate',exact:true})
 await hm.getByText('Awake',{exact:true}).waitFor()
 const widths=await hm.evaluate(el=>[el.scrollWidth,innerWidth])
 assert(widths[0]<=widths[1],String(widths))
 if(process.env.SMOKE_SCREENSHOTS)await phone.screenshot({path:'/tmp/rov-v3-mobile.png',timeout:20000})
 await hm.getByRole('button',{name:'สกิล',exact:true}).tap()
 assert(await hm.getByRole('heading',{name:'สกิลและลำดับอัป'}).evaluate(el=>document.activeElement===el))
 await hm.getByRole('button',{name:'ปิดรายละเอียดฮีโร่'}).tap()
 await sheet.waitFor()
 assert(await sheet.getByRole('button',{name:'รายละเอียด Hayate',exact:true}).evaluate(el=>document.activeElement===el))
 await sheet.getByRole('button',{name:'ฮีโร่ Hayate',exact:true}).tap()
 await phone.getByRole('button',{name:'ยืนยันเลือก'}).tap()
 await phone.getByRole('button',{name:'คู่แข่ง แครี่ Hayate'}).waitFor()
 assert.deepEqual(errors,[])
 console.log('Hero intel passed: hover, skill/build sources, situational, clipboard, fallback, mobile nested dialogs and preserved draft')
}finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
